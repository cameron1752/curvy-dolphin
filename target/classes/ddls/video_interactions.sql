CREATE TABLE IF NOT EXISTS curvy_dolphin.video_interactions
(
    id              BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT NOT NULL,
    video_id        UUID NOT NULL,
    event_type      VARCHAR(30) NOT NULL,
    watch_duration  BIGINT,
    video_duration  BIGINT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    latitude        DOUBLE PRECISION,
    longitude       DOUBLE PRECISION,

    CONSTRAINT video_interactions_pkey
    PRIMARY KEY (id),

    CONSTRAINT fk_video_interactions_user
    FOREIGN KEY (user_id)
    REFERENCES curvy_dolphin.users (user_id)
    ON DELETE CASCADE,

    CONSTRAINT fk_video_interactions_video
    FOREIGN KEY (video_id)
    REFERENCES curvy_dolphin.videos (id)
    ON DELETE CASCADE,

    CONSTRAINT chk_video_interactions_event_type
    CHECK (
              event_type IN (
              'IMPRESSION',
              'PLAY',
              'WATCH_25',
              'WATCH_50',
              'WATCH_75',
              'WATCH_COMPLETE',
              'LIKE',
              'COMMENT',
              'SHARE',
              'SKIP'
                            )
    ),

    CONSTRAINT chk_video_interactions_latitude
    CHECK (latitude BETWEEN -90 AND 90),

    CONSTRAINT chk_video_interactions_longitude
    CHECK (longitude BETWEEN -180 AND 180)
    );

CREATE INDEX idx_video_interactions_video_id
    ON curvy_dolphin.video_interactions (video_id);

CREATE INDEX idx_video_interactions_user_id
    ON curvy_dolphin.video_interactions (user_id);

CREATE INDEX idx_video_interactions_event_type
    ON curvy_dolphin.video_interactions (event_type);

CREATE INDEX idx_video_interactions_created_at
    ON curvy_dolphin.video_interactions (created_at DESC);