-- ============================================================
-- curvy_dolphin schema: full rebuild
-- Drops all tables (children first) and recreates them
-- (parents first) with all constraints and indexes.
-- ============================================================

CREATE SCHEMA IF NOT EXISTS curvy_dolphin;

-- ------------------------------------------------------------
-- DROP TABLES (children -> parents, CASCADE to be safe)
-- ------------------------------------------------------------
DROP TABLE IF EXISTS curvy_dolphin.comments CASCADE;
DROP TABLE IF EXISTS curvy_dolphin.video_likes CASCADE;
DROP TABLE IF EXISTS curvy_dolphin.video_shares CASCADE;
DROP TABLE IF EXISTS curvy_dolphin.video_interactions CASCADE;
DROP TABLE IF EXISTS curvy_dolphin.videos CASCADE;
DROP TABLE IF EXISTS curvy_dolphin.users CASCADE;

-- ============================================================
-- CREATE TABLES (parents -> children)
-- ============================================================

-- ------------------------------------------------------------
-- Table: curvy_dolphin.users
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS curvy_dolphin.users
(
    user_id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 9223372036854775807 CACHE 1 ),
    username character varying(255) COLLATE pg_catalog."default",
    provider_id character varying(255) COLLATE pg_catalog."default",
    email character varying(255) COLLATE pg_catalog."default",
    name character varying(255) COLLATE pg_catalog."default",
    avatar_url character varying(255) COLLATE pg_catalog."default",
    created_at timestamp,
    CONSTRAINT users_pkey PRIMARY KEY (user_id),
    CONSTRAINT users_provider_id_unique UNIQUE (provider_id)
    )
    TABLESPACE pg_default;

ALTER TABLE IF EXISTS curvy_dolphin.users
    OWNER to postgres;

-- ------------------------------------------------------------
-- Table: curvy_dolphin.videos
-- ------------------------------------------------------------
CREATE TABLE curvy_dolphin.videos (
                                      id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
                                      user_id        BIGINT NOT NULL,
                                      video_url      TEXT NOT NULL,
                                      thumbnail_url  TEXT,
                                      latitude       DOUBLE PRECISION,
                                      longitude      DOUBLE PRECISION,
                                      location_id    BIGINT,
                                      caption        TEXT,
                                      created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
                                      visibility     VARCHAR(20) NOT NULL DEFAULT 'PUBLIC',

                                      CONSTRAINT fk_videos_user
                                          FOREIGN KEY (user_id) REFERENCES curvy_dolphin.users (user_id),

                                      CONSTRAINT chk_videos_visibility
                                          CHECK (visibility IN ('PUBLIC', 'PRIVATE', 'FRIENDS')),

                                      CONSTRAINT chk_videos_latitude
                                          CHECK (latitude BETWEEN -90 AND 90),

                                      CONSTRAINT chk_videos_longitude
                                          CHECK (longitude BETWEEN -180 AND 180)
);

CREATE INDEX idx_videos_user_id ON curvy_dolphin.videos (user_id);
CREATE INDEX idx_videos_created_at ON curvy_dolphin.videos (created_at DESC);

ALTER TABLE IF EXISTS curvy_dolphin.videos
    OWNER to postgres;

-- ------------------------------------------------------------
-- Table: curvy_dolphin.video_interactions
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS curvy_dolphin.video_interactions
(
    id              BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT NOT NULL,
    video_id        UUID NOT NULL,
    event_type      VARCHAR(30) NOT NULL,
    watch_duration  BIGINT,
    video_duration  BIGINT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    latitude        DOUBLE PRECISION,
    longitude       DOUBLE PRECISION,

    CONSTRAINT video_interactions_pkey
    PRIMARY KEY (id),

    CONSTRAINT fk_video_interactions_user
    FOREIGN KEY (user_id)
    REFERENCES curvy_dolphin.users (user_id)
    ON DELETE CASCADE,

    CONSTRAINT fk_video_interactions_video
    FOREIGN KEY (video_id)
    REFERENCES curvy_dolphin.videos (id)
    ON DELETE CASCADE,

    CONSTRAINT chk_video_interactions_event_type
    CHECK (
              event_type IN (
              'IMPRESSION',
              'PLAY',
              'WATCH_25',
              'WATCH_50',
              'WATCH_75',
              'WATCH_COMPLETE',
              'LIKE',
              'COMMENT',
              'SHARE',
              'SKIP'
                            )
    ),

    CONSTRAINT chk_video_interactions_latitude
    CHECK (latitude BETWEEN -90 AND 90),

    CONSTRAINT chk_video_interactions_longitude
    CHECK (longitude BETWEEN -180 AND 180)
    );

CREATE INDEX idx_video_interactions_video_id
    ON curvy_dolphin.video_interactions (video_id);

CREATE INDEX idx_video_interactions_user_id
    ON curvy_dolphin.video_interactions (user_id);

CREATE INDEX idx_video_interactions_event_type
    ON curvy_dolphin.video_interactions (event_type);

CREATE INDEX idx_video_interactions_created_at
    ON curvy_dolphin.video_interactions (created_at DESC);

